import { build } from 'esbuild'
import { readFile, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const projectRoot = fileURLToPath(new URL('../', import.meta.url))
const upstreamRoot = path.join(projectRoot, 'src/client/board/upstream')
const clientRoot = path.join(upstreamRoot, 'client')
export const upstreamCssFiles = [
  'tasks-graph.module.css',
  'tasks-canvas.module.css',
  'FloatingWindow.module.css',
  'context-diagnostics.module.css',
  'SubagentView.module.css',
]

/** Compile the original CSS Modules with esbuild's local-css loader. */
export async function compileUpstreamCss(filename, contents) {
  const virtualName = `dsh-maestro-upstream-${filename}`
  const result = await build({
    stdin: {
      contents: `import styles from ${JSON.stringify(virtualName)}; export default styles;`,
      sourcefile: 'upstream-css-entry.js',
      resolveDir: projectRoot,
    },
    bundle: true,
    write: false,
    outdir: path.join(projectRoot, '.tmp/upstream-css-output'),
    platform: 'neutral',
    format: 'esm',
    charset: 'utf8',
    minify: false,
    legalComments: 'none',
    logLevel: 'silent',
    plugins: [{
      name: 'original-upstream-css',
      setup(builder) {
        builder.onResolve({ filter: /^dsh-maestro-upstream-.*\.module\.css$/ }, () => ({
          path: virtualName,
          namespace: 'upstream-css',
        }))
        builder.onLoad({ filter: /.*/, namespace: 'upstream-css' }, () => ({
          contents,
          loader: 'local-css',
        }))
      },
    }],
  })
  const javascript = result.outputFiles.find(file => file.path.endsWith('.js'))?.text
  const stylesheet = result.outputFiles.find(file => file.path.endsWith('.css'))?.text
  if (javascript === undefined || stylesheet === undefined) {
    throw new Error(`CSS compilation produced no module or stylesheet: ${filename}`)
  }
  // This module contains only the class/keyframe map emitted by the CSS compiler.
  const { default: classes } = await import(`data:text/javascript;base64,${Buffer.from(javascript).toString('base64')}`)
  return { classes, stylesheet }
}

/** Generated TS is committed, and refreshed before build, typecheck and tests. */
export async function generateUpstreamCss() {
  for (const filename of upstreamCssFiles) {
    const input = path.join(clientRoot, filename)
    const { classes, stylesheet } = await compileUpstreamCss(filename, await readFile(input, 'utf8'))
    const id = `dsh-maestro-upstream-${filename.replaceAll('.', '-')}`
    const source = [
      '// Generated by scripts/build-upstream-css.mjs. Edit the original .css file.',
      '// DSH-better-sidebar 0.28.2, MIT; see THIRD_PARTY_NOTICES.',
      "import { injectUpstreamStylesheet } from '../style-runtime.js'",
      `const css: Record<string, string> = ${JSON.stringify(classes, null, 2)}`,
      `export const stylesheetId = ${JSON.stringify(id)}`,
      `export const stylesheetText = ${JSON.stringify(stylesheet)}`,
      'injectUpstreamStylesheet(stylesheetId, stylesheetText)',
      'export default css',
      '',
    ].join('\n')
    const output = `${input}.ts`
    const previous = await readFile(output, 'utf8').catch(() => undefined)
    if (previous !== source) await writeFile(output, source)
  }
}

/** Shared tsdown/Vitest resolver; no CSS asset is left for the host to discover. */
export function upstreamCssPlugin({ injectIntoEntry = true } = {}) {
  return {
    name: 'dsh-maestro-upstream-css',
    enforce: 'pre',
    async buildStart() {
      await generateUpstreamCss()
      for (const filename of upstreamCssFiles) this.addWatchFile?.(path.join(clientRoot, filename))
    },
    resolveId(source, importer) {
      if (source === 'clsx') return path.join(upstreamRoot, 'vendor/clsx/dist/clsx.mjs')
      if (source === '@formkit/auto-animate') return path.join(upstreamRoot, 'vendor/auto-animate/index.mjs')
      // TypeScript sees the upstream declaration tree; the runtime keeps the
      // original .ts/.tsx implementations and their original signatures.
      if (source.startsWith('./.types/') && importer !== undefined) {
        const resolved = path.resolve(path.dirname(importer), source)
        const declarationRoot = path.join(upstreamRoot, '.types')
        if (resolved.startsWith(`${declarationRoot}${path.sep}`)) {
          const original = path.join(upstreamRoot, path.relative(declarationRoot, resolved)).replace(/\.js$/, '')
          for (const extension of ['.tsx', '.ts']) {
            if (existsSync(`${original}${extension}`)) return `${original}${extension}`
          }
        }
      }
      if (source.endsWith('.module.css') && importer !== undefined) {
        const resolved = path.resolve(path.dirname(importer), source)
        if (resolved.startsWith(`${clientRoot}${path.sep}`)) return `${resolved}.ts`
      }
      return undefined
    },
    transform(code, id) {
      if (injectIntoEntry && path.resolve(id) === path.join(projectRoot, 'src/client/index.ts')) {
        return { code: `${code}\nimport './board/upstream/styles.ts'\n`, map: null }
      }
      return undefined
    },
  }
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  await generateUpstreamCss()
  process.stdout.write(`Generated ${upstreamCssFiles.length} upstream CSS Modules with inline styles.\n`)
}
